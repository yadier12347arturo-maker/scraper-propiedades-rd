class BaseScraper:
    source = ""
    base_url = ""
    card_selectors = []
    link_selector = "a[href]"
    selectors = {}
    detail_seller_selectors = []

    def page_url(self, page):
        raise NotImplementedError

    def __init__(self, target=200, delay=1.0, max_pages=60, enrich_detail=True):
        self.target = target
        self.delay = delay
        self.max_pages = max_pages
        self.enrich_detail = enrich_detail
        self.session = requests.Session()
        self.session.headers.update(HEADERS)
        self.request_log = []
        self.properties = []

    def fetch(self, url):
        start = time.perf_counter()
        status = None
        try:
            resp = self.session.get(url, timeout=25)
            status = resp.status_code
            resp.raise_for_status()
            soup = BeautifulSoup(resp.text, "lxml")
        except requests.RequestException as exc:
            print(f"[{self.source}] error en {url}: {exc}")
            soup = None
        elapsed = time.perf_counter() - start
        self.request_log.append({"source": self.source, "url": url,
                                 "status": status, "seconds": round(elapsed, 3)})
        time.sleep(self.delay)
        return soup

    def get_cards(self, soup):
        for sel in self.card_selectors:
            cards = soup.select(sel)
            if cards:
                return cards
        return []

    @staticmethod
    def _first_text(node, selectors):
        for sel in selectors or []:
            el = node.select_one(sel)
            if el and clean(el.get_text(" ")):
                return clean(el.get_text(" "))
        return None

    def parse_card(self, card):
        text = clean(card.get_text(" ")) or ""
        a = card if card.name == "a" else card.select_one(self.link_selector)
        link = urljoin(self.base_url, a["href"]) if a and a.get("href") else None

        name = self._first_text(card, self.selectors.get("name")) \
            or self._first_text(card, ["h1", "h2", "h3", "h4"]) \
            or (clean(a.get_text(" ")) if a else None)

        price_text = self._first_text(card, self.selectors.get("price")) or find_price_text(text)
        price, currency = parse_price(price_text)

        return {
            "Fuente": self.source,
            "Nombre": name,
            "Precio": price,
            "Moneda": currency,
            "Ubicacion": self._first_text(card, self.selectors.get("location")) or "República Dominicana",
            "Vendedor": self._first_text(card, self.selectors.get("seller")),
            "Tamano_m2": extract_size(text),
            "Habitaciones": extract_count(text, ["hab", "habitaci", "cuartos", "dorm", "bed"]),
            "Banos": extract_count(text, ["bano", "baño", "bath", "wc"]),
            "Parqueos": extract_count(text, ["parqueo", "park", "garaje", "garage", "estacionamiento"]),
            "Link": link,
        }

    def enrich(self, prop):
        if prop["Vendedor"] or not prop["Link"] or not self.detail_seller_selectors:
            return
        soup = self.fetch(prop["Link"])
        if soup:
            prop["Vendedor"] = self._first_text(soup, self.detail_seller_selectors)

    def scrape(self):
        seen = set()
        for page in range(1, self.max_pages + 1):
            if len(self.properties) >= self.target:
                break
            soup = self.fetch(self.page_url(page))
            if soup is None:
                break
            cards = self.get_cards(soup)
            new = 0
            for card in cards:
                prop = self.parse_card(card)
                key = prop["Link"] or prop["Nombre"]
                if not key or key in seen:
                    continue
                seen.add(key)
                new += 1
                if self.enrich_detail:
                    self.enrich(prop)
                self.properties.append(prop)
                if len(self.properties) >= self.target:
                    break
            print(f"[{self.source}] pagina {page}: +{new} (total {len(self.properties)})")
            if new == 0:
                break
        return self.properties[: self.target]

